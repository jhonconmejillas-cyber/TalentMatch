-- =====================================================================
-- TalentMatch - V5: bitacora de accesos denegados (HU-006, RNF-10)
-- Cada intento de ver informacion sin permiso queda registrado.
-- Igual que bitacora_calculo, es de solo lectura para la aplicacion.
-- =====================================================================
CREATE TABLE bitacora_acceso (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    recurso    VARCHAR(300) NOT NULL,
    motivo     VARCHAR(300) NOT NULL,
    fecha      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_bitacora_acceso_fecha ON bitacora_acceso (fecha DESC);

CREATE FUNCTION bitacora_acceso_solo_lectura() RETURNS TRIGGER AS $$
BEGIN
    -- Unica excepcion: al borrar un usuario, ON DELETE SET NULL deja el registro sin usuario.
    IF TG_OP = 'UPDATE' AND NEW.usuario_id IS NULL AND NEW.recurso = OLD.recurso
            AND NEW.motivo = OLD.motivo AND NEW.fecha = OLD.fecha THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'bitacora_acceso es de solo lectura (RNF-10)';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_bitacora_acceso_solo_lectura
    BEFORE UPDATE OR DELETE ON bitacora_acceso
    FOR EACH ROW EXECUTE FUNCTION bitacora_acceso_solo_lectura();
