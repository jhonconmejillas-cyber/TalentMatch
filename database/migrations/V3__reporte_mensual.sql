-- =====================================================================
-- TalentMatch - V3: registro de los reportes mensuales de rechazos (HU-002)
--
-- El contenido del reporte se calcula a partir de las postulaciones resueltas
-- (cuyo puntaje proviene de la bitacora de calculo); esta tabla deja constancia
-- de que el proceso nocturno lo genero cada mes sin intervencion manual.
-- =====================================================================
CREATE TABLE reporte_mensual (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo          VARCHAR(7)  NOT NULL UNIQUE,   -- AAAA-MM
    fecha_generacion TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    managers         INTEGER     NOT NULL,
    anomalias        INTEGER     NOT NULL
);
