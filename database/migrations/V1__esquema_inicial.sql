-- ---------------------------------------------------------------------
-- Usuarios. Una sola tabla para todos los roles (herencia SINGLE_TABLE):
-- la columna "rol" dice que clase de Java es cada fila.
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol             VARCHAR(20)  NOT NULL
                    CHECK (rol IN ('EMPLEADO', 'MANAGER', 'RRHH', 'LIDER_EJECUTIVO', 'ADMIN')),
    nombre          VARCHAR(120) NOT NULL,
    correo          VARCHAR(160) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(100) NOT NULL,          -- BCrypt, nunca texto plano (RNF-07)
    activo          BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Datos profesionales de los usuarios con rol EMPLEADO o MANAGER (Manager hereda de Empleado).
CREATE TABLE empleado (
    id                    BIGINT PRIMARY KEY REFERENCES usuario (id) ON DELETE CASCADE,
    senioridad            VARCHAR(20) CHECK (senioridad IN ('JUNIOR', 'SEMI_SENIOR', 'SENIOR', 'LIDER')),
    anios_experiencia     INTEGER     NOT NULL DEFAULT 0 CHECK (anios_experiencia >= 0),
    area                  VARCHAR(80),
    fecha_inicio_rol      DATE,       -- RN-07: antiguedad minima de 6 meses
    fecha_ingreso_empresa DATE,       -- RN-21: anios en la empresa
    manager_id            BIGINT REFERENCES empleado (id)   -- RN-19: manager actual
);

-- ---------------------------------------------------------------------
-- Habilidades
-- ---------------------------------------------------------------------
CREATE TABLE habilidad (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE
);

-- RN-19: toda habilidad nace AGREGADO; solo AVALADO entra al calculo (RN-20).
CREATE TABLE habilidad_empleado (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id     BIGINT      NOT NULL REFERENCES empleado (id) ON DELETE CASCADE,
    habilidad_id    BIGINT      NOT NULL REFERENCES habilidad (id),
    estado          VARCHAR(20) NOT NULL DEFAULT 'AGREGADO'
                    CHECK (estado IN ('AGREGADO', 'AVALADO', 'RECHAZADO')),
    nivel_declarado VARCHAR(40),
    fecha_agregado  DATE        NOT NULL DEFAULT CURRENT_DATE,
    fecha_aval      TIMESTAMP,
    avalado_por     BIGINT REFERENCES empleado (id),
    UNIQUE (empleado_id, habilidad_id),
    -- Una habilidad avalada siempre sabe quien y cuando la avalo.
    CHECK (estado = 'AGREGADO' OR (fecha_aval IS NOT NULL AND avalado_por IS NOT NULL))
);

-- RF-09: habilidades que el empleado quiere aprender.
CREATE TABLE wishlist (
    empleado_id  BIGINT NOT NULL REFERENCES empleado (id) ON DELETE CASCADE,
    habilidad_id BIGINT NOT NULL REFERENCES habilidad (id),
    PRIMARY KEY (empleado_id, habilidad_id)
);

-- ---------------------------------------------------------------------
-- Proyectos y asignaciones
-- ---------------------------------------------------------------------
CREATE TABLE proyecto (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    area   VARCHAR(80)  NOT NULL,
    estado VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO' CHECK (estado IN ('ACTIVO', 'CERRADO'))
);

-- RN-02: al liberarse una asignacion (fecha_fin) se genera una vacante.
CREATE TABLE asignacion_proyecto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id  BIGINT       NOT NULL REFERENCES empleado (id) ON DELETE CASCADE,
    proyecto_id  BIGINT       NOT NULL REFERENCES proyecto (id),
    cargo        VARCHAR(120) NOT NULL,
    fecha_inicio DATE         NOT NULL,
    fecha_fin    DATE,
    motivo_fin   VARCHAR(30)
                 CHECK (motivo_fin IN ('RENUNCIA', 'ROTACION_ACEPTADA', 'CIERRE_PROYECTO')),
    CHECK ((fecha_fin IS NULL) = (motivo_fin IS NULL)),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- Un empleado tiene como maximo una asignacion vigente.
CREATE UNIQUE INDEX ux_asignacion_vigente ON asignacion_proyecto (empleado_id) WHERE fecha_fin IS NULL;

-- ---------------------------------------------------------------------
-- Vacantes
-- ---------------------------------------------------------------------
CREATE TABLE vacante (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo           VARCHAR(120) NOT NULL,
    descripcion      TEXT,
    senioridad       VARCHAR(20)  NOT NULL
                     CHECK (senioridad IN ('JUNIOR', 'SEMI_SENIOR', 'SENIOR', 'LIDER')),
    area             VARCHAR(80)  NOT NULL,
    estado           VARCHAR(25)  NOT NULL DEFAULT 'BORRADOR'
                     CHECK (estado IN ('BORRADOR', 'PENDIENTE_ACTIVACION', 'ACTIVA', 'CERRADA', 'DESCARTADA')),
    origen           VARCHAR(25)  NOT NULL DEFAULT 'MANUAL'
                     CHECK (origen IN ('MANUAL', 'RENUNCIA', 'ROTACION_ACEPTADA', 'CAMBIO_PROYECTO')),
    fecha_creacion   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_activacion TIMESTAMP,   -- RN-03: en PENDIENTE_ACTIVACION es la fecha programada
    fecha_cierre     TIMESTAMP,
    manager_id       BIGINT REFERENCES empleado (id),   -- manager solicitante (RF-11)
    proyecto_id      BIGINT REFERENCES proyecto (id)
);

-- RF-11: habilidades criticas y deseables de la vacante.
CREATE TABLE vacante_habilidad_critica (
    vacante_id   BIGINT NOT NULL REFERENCES vacante (id) ON DELETE CASCADE,
    habilidad_id BIGINT NOT NULL REFERENCES habilidad (id),
    PRIMARY KEY (vacante_id, habilidad_id)
);

CREATE TABLE vacante_habilidad_deseable (
    vacante_id   BIGINT NOT NULL REFERENCES vacante (id) ON DELETE CASCADE,
    habilidad_id BIGINT NOT NULL REFERENCES habilidad (id),
    PRIMARY KEY (vacante_id, habilidad_id)
);

-- ---------------------------------------------------------------------
-- Postulaciones
-- ---------------------------------------------------------------------
CREATE TABLE postulacion (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id      BIGINT           NOT NULL REFERENCES empleado (id) ON DELETE CASCADE,
    vacante_id       BIGINT           NOT NULL REFERENCES vacante (id),
    match_score      DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (match_score BETWEEN 0 AND 100),
    puntaje_final    DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (puntaje_final BETWEEN 0 AND 100),
    estado           VARCHAR(25)      NOT NULL DEFAULT 'ACTIVA'
                     CHECK (estado IN ('ACTIVA', 'ACEPTADA', 'RECHAZADA', 'CANCELADA_POR_ROTACION')),
    fecha_creacion   TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_resolucion TIMESTAMP,
    posicion_ranking INTEGER,         -- HU-004: "Fuiste #1 de 12"
    total_candidatos INTEGER
);

-- Un empleado no puede tener dos postulaciones activas a la misma vacante.
CREATE UNIQUE INDEX ux_postulacion_activa ON postulacion (empleado_id, vacante_id) WHERE estado = 'ACTIVA';

-- ---------------------------------------------------------------------
-- Bitacora del calculo (RNF-06): solo se insertan filas, nunca se modifican.
-- ---------------------------------------------------------------------
CREATE TABLE bitacora_calculo (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empleado_id     BIGINT           NOT NULL REFERENCES empleado (id),
    vacante_id      BIGINT           NOT NULL REFERENCES vacante (id),
    match_score     DOUBLE PRECISION NOT NULL,
    puntaje_final   DOUBLE PRECISION NOT NULL,
    umbral_aplicado DOUBLE PRECISION NOT NULL,
    fecha_hora      TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    detalle         TEXT
);

-- La base de datos rechaza cualquier UPDATE o DELETE sobre la bitacora,
-- aunque el codigo de la aplicacion tuviera un error.
CREATE FUNCTION bitacora_calculo_solo_lectura() RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'bitacora_calculo es de solo lectura (RNF-06)';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tr_bitacora_calculo_solo_lectura
    BEFORE UPDATE OR DELETE ON bitacora_calculo
    FOR EACH ROW EXECUTE FUNCTION bitacora_calculo_solo_lectura();

-- ---------------------------------------------------------------------
-- Alertas para RR.HH. (RN-29, RN-30)
-- ---------------------------------------------------------------------
CREATE TABLE alerta (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo             VARCHAR(30) NOT NULL CHECK (tipo IN ('RECHAZOS_REPETIDOS', 'VACANTE_SIN_MATCH')),
    estado           VARCHAR(20) NOT NULL DEFAULT 'ABIERTA' CHECK (estado IN ('ABIERTA', 'RESUELTA')),
    fecha            TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    manager_id       BIGINT REFERENCES empleado (id),
    vacante_id       BIGINT REFERENCES vacante (id),
    detalle          TEXT,
    atendida_por     BIGINT REFERENCES usuario (id),
    fecha_resolucion TIMESTAMP
);

-- ---------------------------------------------------------------------
-- Notificaciones in-app (RNF-08)
-- ---------------------------------------------------------------------
CREATE TABLE notificacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario_id BIGINT       NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    tipo            VARCHAR(30)  NOT NULL
                    CHECK (tipo IN ('RESULTADO_POSTULACION', 'ROTACION_ACEPTADA', 'ROTACION_CONFIRMADA',
                                    'VACANTE_WISHLIST', 'VACANTE_SIN_MATCH', 'ALERTA')),
    titulo          VARCHAR(160) NOT NULL,
    mensaje         TEXT         NOT NULL,
    fecha           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    leida           BOOLEAN      NOT NULL DEFAULT FALSE,
    postulacion_id  BIGINT REFERENCES postulacion (id),
    vacante_id      BIGINT REFERENCES vacante (id)
);

-- ---------------------------------------------------------------------
-- Indices de las consultas mas frecuentes
-- ---------------------------------------------------------------------
CREATE INDEX ix_empleado_manager           ON empleado (manager_id);
CREATE INDEX ix_habilidad_empleado_estado  ON habilidad_empleado (empleado_id, estado);
CREATE INDEX ix_vacante_estado             ON vacante (estado);
CREATE INDEX ix_postulacion_vacante        ON postulacion (vacante_id, estado);
CREATE INDEX ix_postulacion_empleado       ON postulacion (empleado_id, estado);
CREATE INDEX ix_bitacora_empleado_vacante  ON bitacora_calculo (empleado_id, vacante_id);
CREATE INDEX ix_notificacion_destinatario  ON notificacion (destinatario_id, leida);
CREATE INDEX ix_alerta_estado              ON alerta (estado);
